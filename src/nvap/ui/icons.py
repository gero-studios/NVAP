def _wrap_svg(inner: str, color: str, stroke_width: float = 2.0) -> bytes:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" '
        f'fill="none" stroke="{color}" stroke-width="{stroke_width}" '
        f'stroke-linecap="round" stroke-linejoin="round">{inner}</svg>'
    ).encode("utf-8")


def _render_pixmap(name: str, size: int, color: str, dpr: float = 2.0) -> QPixmap:
    inner = _ICONS.get(name)
    if inner is None:
        # Unknown icon – render a fallback square so missing names are visible.
        inner = '<rect x="4" y="4" width="16" height="16" rx="2"/>'
    svg_bytes = _wrap_svg(inner, color)
    renderer = QSvgRenderer(QByteArray(svg_bytes))
    px = QPixmap(int(size * dpr), int(size * dpr))
    px.setDevicePixelRatio(dpr)
    px.fill(Qt.GlobalColor.transparent)
    painter = QPainter(px)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing, True)
    painter.setRenderHint(QPainter.RenderHint.SmoothPixmapTransform, True)
    renderer.render(painter)
    painter.end()
    return px


def icon(name: str, size: int = ICON_MD, color: str | None = None) -> QIcon:
    """Return a tinted QIcon by Lucide name. Color defaults to text_secondary."""
    color = color or COLOR.text_secondary
    qicon = QIcon()
    # Provide both normal and ~retina pixmaps for crisp rendering.
    qicon.addPixmap(_render_pixmap(name, size, color, dpr=1.0))
    qicon.addPixmap(_render_pixmap(name, size, color, dpr=2.0))
    return qicon


def icon_pixmap(name: str, size: int = ICON_MD, color: str | None = None) -> QPixmap:
    """Return a tinted QPixmap (handy for QLabel)."""
    color = color or COLOR.text_secondary
    return _render_pixmap(name, size, color, dpr=2.0)


def has_icon(name: str) -> bool:
    return name in _ICONS


def icon_size(size: int = ICON_MD) -> QSize:
    return QSize(size, size)
